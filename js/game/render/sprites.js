// Loads the image of the fighter's current sprite (a sprite without an entry keeps the previous image).
export function selectSprite(rt, fighter, table) {
  const entry = table[fighter.sprite];
  if (!entry) return;
  fighter.image = rt.loadimage(entry[0], entry[2]);
  fighter.imageDirection = entry[1];
}
